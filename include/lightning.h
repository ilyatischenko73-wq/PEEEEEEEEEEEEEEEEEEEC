#ifndef PEEC_LIGHTNING_H
#define PEEC_LIGHTNING_H

#include "mesh.h"

#include <stddef.h>


/*
 * ============================================================
 * ФОРМА ТОКА МОЛНИИ
 * ============================================================
 *
 * Пока используем двойную экспоненту:
 *
 *     I_L(t) =
 *
 *     K [
 *         exp(-alpha*t)
 *         -
 *         exp(-beta*t)
 *       ].
 *
 *
 * При:
 *
 *     beta > alpha > 0
 *
 * ток:
 *
 *     I_L(0) = 0
 *
 * затем быстро нарастает и медленно спадает.
 */
typedef enum
{
    LIGHTNING_WAVE_DOUBLE_EXPONENTIAL = 0

} LightningWaveType;


/*
 * ============================================================
 * ПАРАМЕТРЫ МОЛНИИ
 * ============================================================
 */
typedef struct
{
    LightningWaveType wave_type;

    /*
     * Масштаб двойной экспоненты [A].
     *
     * Важно:
     *
     * K не обязательно равен пиковому току.
     */
    double K;

    /*
     * Медленная постоянная спада [1/s].
     */
    double alpha;

    /*
     * Быстрая постоянная фронта [1/s].
     */
    double beta;

    /*
     * Момент начала импульса [s].
     *
     * При:
     *
     *     t < delay
     *
     * ток равен нулю.
     */
    double delay;

    /*
     * Узел ввода тока в корпус.
     */
    size_t strike_node;

    /*
     * Узел возврата тока.
     *
     * Для замкнутой задачи:
     *
     *     I_s[strike] = +I_L
     *     I_s[return] = -I_L.
     */
    size_t return_node;

} LightningSource;


/*
 * ============================================================
 * ЗНАЧЕНИЯ ПО УМОЛЧАНИЮ
 * ============================================================
 *
 * Используем стартовые параметры:
 *
 *     K     = 102900 A
 *     alpha = 1500 1/s
 *     beta  = 1e6 1/s
 *
 *     delay = 0.
 *
 *
 * Номера узлов пользователь должен установить отдельно.
 */
void lightning_source_default(
    LightningSource *source
);


/*
 * ============================================================
 * ПРОВЕРКА ПАРАМЕТРОВ
 * ============================================================
 */
int lightning_source_validate(
    const LightningSource *source,
    size_t n_nodes
);


/*
 * ============================================================
 * ТОК МОЛНИИ
 * ============================================================
 *
 * Возвращает:
 *
 *     I_L(t) [A].
 */
double lightning_current(
    const LightningSource *source,
    double time
);


/*
 * ============================================================
 * ПИК ТОКА
 * ============================================================
 *
 * Для двойной экспоненты аналитически вычисляет:
 *
 *     t_peak
 *     I_peak.
 *
 *
 * t_peak задаётся относительно абсолютного времени,
 * поэтому delay учитывается.
 */
int lightning_peak(
    const LightningSource *source,
    double *time_peak,
    double *current_peak
);


/*
 * ============================================================
 * ПОСТРОЕНИЕ УЗЛОВОГО ИСТОЧНИКА
 * ============================================================
 *
 * Формирует:
 *
 *     I_s[j] [A].
 *
 *
 * Все элементы сначала обнуляются.
 *
 * Затем:
 *
 *     I_s[strike_node] = +I_L(t)
 *     I_s[return_node] = -I_L(t).
 */
int lightning_build_node_current(
    const LightningSource *source,
    size_t n_nodes,
    double time,
    double *node_current
);


/*
 * ============================================================
 * ПОИСК БЛИЖАЙШЕГО УЗЛА
 * ============================================================
 *
 * Полезно для реального корпуса:
 *
 * пользователь задаёт координату точки удара,
 * а программа выбирает ближайший узел сетки.
 *
 *
 * point:
 *
 *     x y z [m].
 */
int lightning_find_nearest_node(
    const Mesh *mesh,
    const double point[3],
    size_t *node_id,
    double *distance
);


/*
 * ============================================================
 * ДИАГНОСТИКА
 * ============================================================
 */
void lightning_print_info(
    const LightningSource *source,
    const Mesh *mesh
);


#endif
