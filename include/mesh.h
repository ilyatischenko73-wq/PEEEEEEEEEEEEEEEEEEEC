#ifndef PEEC_MESH_H
#define PEEC_MESH_H

#include <stddef.h>

/*
 * Унифицированное представление поверхностной сетки.
 *
 * Вычислительное ядро PEEC/ЧЭС работает только с этой структурой.
 * Конкретный формат файла (Gmsh, VTK, OBJ и т.п.) должен преобразовываться
 * в Mesh отдельным модулем чтения.
 */
typedef struct
{
    /*
     * Количество узлов, четырехугольных ячеек и уникальных ребер.
     */
    size_t n_nodes;
    size_t n_quads;
    size_t n_edges;

    /*
     * Координаты узлов:
     *
     * xyz[3*i + 0] = x_i
     * xyz[3*i + 1] = y_i
     * xyz[3*i + 2] = z_i
     *
     * Единицы: м.
     */
    double *xyz;

    /*
     * Связность четырехугольных ячеек.
     *
     * Для каждой ячейки хранятся 4 локальных индекса узлов:
     *
     * quads[4*c + 0]
     * quads[4*c + 1]
     * quads[4*c + 2]
     * quads[4*c + 3]
     */
    int *quads;

    /*
     * Связность глобальных уникальных ребер.
     *
     * Для каждого ребра:
     *
     * edges[2*e + 0] = a
     * edges[2*e + 1] = b
     *
     * Положительное направление тока I_e задается:
     *
     * a -> b.
     */
    int *edges;

    /*
     * Для каждой четырехугольной ячейки хранятся индексы
     * четырех глобальных ребер.
     *
     * cell_edges[4*c + k]
     */
    int *cell_edges;

    /*
     * Ориентация локального ребра ячейки относительно глобального ребра.
     *
     * +1 : локальное и глобальное направления совпадают.
     * -1 : локальное направление противоположно глобальному.
     */
    int *cell_edge_signs;

    /*
     * Векторы глобальных ребер:
     *
     * r_b - r_a
     *
     * Размер: 3 * n_edges.
     * Единицы: м.
     */
    double *edge_vectors;

    /*
     * Длины ребер.
     *
     * Размер: n_edges.
     * Единицы: м.
     */
    double *edge_lengths;

    /*
     * Единичные векторы направления ребер.
     *
     * e_i = (r_b - r_a) / |r_b - r_a|
     *
     * Размер: 3 * n_edges.
     */
    double *edge_directions;

    /*
     * Геометрические центры ребер.
     *
     * Размер: 3 * n_edges.
     * Единицы: м.
     */
    double *edge_centers;

    /*
     * Геометрические центры четырехугольных ячеек.
     *
     * Размер: 3 * n_quads.
     * Единицы: м.
     */
    double *cell_centers;

    /*
     * Площади четырехугольных ячеек.
     *
     * Размер: n_quads.
     * Единицы: м^2.
     */
    double *cell_areas;

    /*
     * Единичные нормали к четырехугольным ячейкам.
     *
     * Размер: 3 * n_quads.
     */
    double *cell_normals;

} Mesh;


/*
 * Обнуляет структуру Mesh.
 *
 * Эту функцию нужно вызывать перед первым использованием объекта Mesh.
 */
void mesh_init(Mesh *mesh);


/*
 * Освобождает всю память, связанную с Mesh.
 */
void mesh_free(Mesh *mesh);


/*
 * Загружает сетку Gmsh.
 *
 * На первом этапе поддерживаем ASCII Gmsh 4.x
 * с четырехугольными поверхностными элементами.
 */
int mesh_load_gmsh(const char *filename, Mesh *mesh);


/*
 * Строит:
 *
 * - уникальные глобальные ребра;
 * - ориентацию ребер;
 * - соответствие ячейка -> ребро;
 * - длины и направления ребер;
 * - центры ребер;
 * - центры, площади и нормали ячеек.
 */
int mesh_build_topology(Mesh *mesh);


/*
 * Печатает краткую информацию о сетке.
 */
void mesh_print_info(const Mesh *mesh);


#endif
