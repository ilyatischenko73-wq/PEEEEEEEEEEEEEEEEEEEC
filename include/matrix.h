#ifndef PEEC_MATRIX_H
#define PEEC_MATRIX_H

#include <stddef.h>


/*
 * ============================================================
 * ПЛОТНАЯ ВЕЩЕСТВЕННАЯ МАТРИЦА
 * ============================================================
 *
 * Матрица хранится в row-major формате:
 *
 *     data[row * cols + col].
 *
 * Например для:
 *
 *     M in R^(m x n)
 *
 * элемент:
 *
 *     M_ij = data[i*n + j].
 */
typedef struct
{
    size_t rows;
    size_t cols;

    double *data;

} Matrix;


/*
 * ============================================================
 * ИНИЦИАЛИЗАЦИЯ
 * ============================================================
 *
 * Создает пустую структуру:
 *
 *     rows = 0
 *     cols = 0
 *     data = NULL.
 */
void matrix_init(Matrix *M);


/*
 * ============================================================
 * ВЫДЕЛЕНИЕ ПАМЯТИ
 * ============================================================
 *
 * Создает матрицу:
 *
 *     rows x cols.
 *
 * Память инициализируется нулями.
 *
 * Возвращает:
 *
 *      0 - успешно;
 *     -1 - ошибка.
 */
int matrix_alloc(
    Matrix *M,
    size_t rows,
    size_t cols
);


/*
 * ============================================================
 * ОСВОБОЖДЕНИЕ ПАМЯТИ
 * ============================================================
 */
void matrix_free(Matrix *M);


/*
 * ============================================================
 * ЗАПОЛНЕНИЕ НУЛЯМИ
 * ============================================================
 */
void matrix_zero(Matrix *M);


/*
 * ============================================================
 * ЗАПОЛНЕНИЕ ОДНИМ ЗНАЧЕНИЕМ
 * ============================================================
 */
void matrix_fill(
    Matrix *M,
    double value
);


/*
 * ============================================================
 * КОПИРОВАНИЕ
 * ============================================================
 *
 * dst получает независимую копию src.
 *
 * Если dst уже содержит память, она освобождается.
 */
int matrix_copy(
    Matrix *dst,
    const Matrix *src
);


/*
 * ============================================================
 * ДОСТУП К ЭЛЕМЕНТУ
 * ============================================================
 *
 * Эти функции не выполняют проверку границ ради скорости.
 */
double matrix_get(
    const Matrix *M,
    size_t row,
    size_t col
);


void matrix_set(
    Matrix *M,
    size_t row,
    size_t col,
    double value
);


/*
 * ============================================================
 * ТРАНСПОНИРОВАНИЕ
 * ============================================================
 *
 * Для:
 *
 *     A in R^(m x n)
 *
 * строит:
 *
 *     AT in R^(n x m).
 *
 * Использует OpenMP.
 */
int matrix_transpose(
    const Matrix *A,
    Matrix *AT,
    int parallel_threads
);


/*
 * ============================================================
 * МАТРИЦА x ВЕКТОР
 * ============================================================
 *
 * Вычисляет:
 *
 *     y = A x.
 *
 * Размер:
 *
 *     A : m x n
 *     x : n
 *     y : m.
 *
 * y должен быть заранее выделен.
 */
int matrix_vector_multiply(
    const Matrix *A,
    const double *x,
    double *y,
    int parallel_threads
);


/*
 * ============================================================
 * МАТРИЦА x МАТРИЦА
 * ============================================================
 *
 * Вычисляет:
 *
 *     C = A B.
 *
 * Размеры:
 *
 *     A : m x k
 *     B : k x n
 *     C : m x n.
 *
 * C выделяется внутри функции.
 */
int matrix_multiply(
    const Matrix *A,
    const Matrix *B,
    Matrix *C,
    int parallel_threads
);


/*
 * ============================================================
 * СЛОЖЕНИЕ МАТРИЦ
 * ============================================================
 *
 * Выполняет:
 *
 *     C = alpha*A + beta*B.
 */
int matrix_linear_combination(
    const Matrix *A,
    double alpha,
    const Matrix *B,
    double beta,
    Matrix *C,
    int parallel_threads
);


/*
 * ============================================================
 * НОРМА INFINITY
 * ============================================================
 *
 * Возвращает:
 *
 *     ||A||_inf =
 *
 *     max_i sum_j |A_ij|.
 */
double matrix_norm_inf(
    const Matrix *A,
    int parallel_threads
);


/*
 * ============================================================
 * МАКСИМАЛЬНЫЙ ЭЛЕМЕНТ ПО МОДУЛЮ
 * ============================================================
 */
double matrix_max_abs(
    const Matrix *A,
    int parallel_threads
);


/*
 * ============================================================
 * ПРОВЕРКА СИММЕТРИИ
 * ============================================================
 *
 * Возвращает:
 *
 *     max |A_ij - A_ji|.
 *
 * Для неквадратной матрицы возвращает NAN.
 */
double matrix_symmetry_error(
    const Matrix *A,
    int parallel_threads
);


/*
 * ============================================================
 * ДИАГНОСТИКА
 * ============================================================
 */
void matrix_print_info(
    const Matrix *M,
    const char *name
);


#endif
