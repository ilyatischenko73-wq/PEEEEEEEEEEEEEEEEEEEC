#ifndef PEEC_LU_H
#define PEEC_LU_H

#include <stddef.h>


/*
 * ============================================================
 * ПАРАМЕТРЫ LU-РАЗЛОЖЕНИЯ
 * ============================================================
 */
typedef struct
{
    /*
     * Количество потоков OpenMP.
     */
    int parallel_threads;

    /*
     * Относительный допуск для определения численной
     * вырожденности матрицы.
     *
     * Проверяется условие:
     *
     *     |pivot| <= pivot_tolerance * matrix_scale.
     *
     * matrix_scale - максимальный по модулю элемент
     * исходной матрицы.
     */
    double pivot_tolerance;

    /*
     * Минимальный размер оставшейся подматрицы,
     * начиная с которого включается OpenMP.
     *
     * На маленьких блоках создание/синхронизация потоков
     * может стоить дороже самого вычисления.
     */
    size_t parallel_threshold;

} LUOptions;


/*
 * ============================================================
 * LU-ФАКТОРИЗАЦИЯ
 * ============================================================
 *
 * Для матрицы:
 *
 *     A in R^(n x n)
 *
 * строится:
 *
 *     P A = L U,
 *
 * где:
 *
 *     P - матрица перестановок;
 *     L - нижняя треугольная матрица;
 *     U - верхняя треугольная матрица.
 *
 *
 * L и U хранятся совместно в одном массиве:
 *
 *             U U U U
 *             L U U U
 *     data =  L L U U
 *             L L L U
 *
 * Диагональ L отдельно не хранится:
 *
 *     L_ii = 1.
 *
 *
 * pivots[k] содержит номер строки, выбранной главным
 * элементом на шаге k.
 */
typedef struct
{
    size_t n;

    /*
     * Совмещенное хранение L и U.
     *
     * Row-major:
     *
     *     data[i*n+j].
     */
    double *data;

    /*
     * История перестановок строк.
     */
    size_t *pivots;

    /*
     * Число перестановок строк.
     *
     * Может быть полезно позже, например для det(A).
     */
    size_t swap_count;

    /*
     * Масштаб исходной матрицы:
     *
     *     max |A_ij|.
     */
    double matrix_scale;

    /*
     * Флаг успешной факторизации.
     */
    int factorized;

} LUFactorization;


/*
 * Устанавливает рекомендуемые параметры.
 */
void lu_options_default(
    LUOptions *options,
    int parallel_threads
);


/*
 * Инициализация пустой структуры.
 */
void lu_init(LUFactorization *lu);


/*
 * Освобождение памяти.
 */
void lu_free(LUFactorization *lu);


/*
 * ============================================================
 * LU-ФАКТОРИЗАЦИЯ
 * ============================================================
 *
 * input:
 *
 *     исходная плотная матрица n x n в row-major формате.
 *
 * Исходная матрица НЕ изменяется.
 *
 * Внутри создается ее копия, которая затем факторизуется.
 *
 *
 * Возвращает:
 *
 *      0 - успешно;
 *     -1 - ошибка аргументов/памяти;
 *     -2 - матрица численно вырождена.
 */
int lu_factorize(
    const double *input,
    size_t n,
    const LUOptions *options,
    LUFactorization *lu
);


/*
 * ============================================================
 * РЕШЕНИЕ ОДНОЙ СИСТЕМЫ
 * ============================================================
 *
 * Решает:
 *
 *     A x = b
 *
 * используя ранее построенное:
 *
 *     P A = L U.
 *
 * b не изменяется.
 *
 * x должен иметь длину n.
 *
 * Допускается:
 *
 *     x == b,
 *
 * то есть решение на месте.
 */
int lu_solve(
    const LUFactorization *lu,
    const double *b,
    double *x
);


/*
 * ============================================================
 * РЕШЕНИЕ НЕСКОЛЬКИХ ПРАВЫХ ЧАСТЕЙ
 * ============================================================
 *
 * Решает:
 *
 *     A X = B.
 *
 *
 * B хранится так:
 *
 *     rhs_count векторов длины n
 *
 * последовательно:
 *
 *     B[0*n + i]
 *     B[1*n + i]
 *     ...
 *
 * То есть каждая правая часть расположена непрерывно.
 *
 * X имеет такой же формат.
 *
 *
 * Разные правые части независимы и распараллеливаются
 * через OpenMP.
 */
int lu_solve_multiple(
    const LUFactorization *lu,
    const double *B,
    double *X,
    size_t rhs_count,
    int parallel_threads
);


/*
 * ============================================================
 * ОПРЕДЕЛИТЕЛЬ
 * ============================================================
 *
 * После LU:
 *
 *     det(A) = sign(P) * product(U_ii).
 *
 * Для очень больших матриц возможны overflow/underflow,
 * поэтому эту функцию следует считать диагностической.
 */
double lu_determinant(const LUFactorization *lu);


/*
 * Печатает краткую информацию о факторизации.
 */
void lu_print_info(const LUFactorization *lu);


#endif
