#ifndef PEEC_QUADRATURE_H
#define PEEC_QUADRATURE_H

#include "dual_mesh.h"


/*
 * ============================================================
 * ТИП ГЕОМЕТРИЧЕСКОЙ ПАРЫ QUADPATCH
 * ============================================================
 *
 * Классификация используется для выбора способа вычисления:
 *
 *              /        /
 *             |        |       1
 *             |        |    ------- dS dS'
 *             |        |    |r-r'|
 *            /Pi_a    /Pi_b
 */
typedef enum
{
    /*
     * Полностью совпадающие области.
     *
     * Интеграл содержит интегрируемую сингулярность:
     *
     *     1 / |r-r'|
     *
     * при:
     *
     *     r -> r'.
     */
    QUAD_PAIR_SELF = 0,

    /*
     * Области имеют хотя бы одну общую вершину.
     *
     * Сюда входят:
     *
     * - общая вершина;
     * - общее ребро.
     */
    QUAD_PAIR_TOUCHING,

    /*
     * Области не соприкасаются, но геометрически близки.
     */
    QUAD_PAIR_NEAR,

    /*
     * Хорошо разделенные области.
     */
    QUAD_PAIR_FAR

} QuadPairType;


/*
 * ============================================================
 * GAUSS-LEGENDRE
 * ============================================================
 *
 * Возвращает узлы x[i] и веса w[i] квадратуры Гаусса-Лежандра
 * на стандартном интервале:
 *
 *     [-1, 1].
 *
 * Поддерживаются порядки:
 *
 *     2
 *     3
 *     4
 *     5
 *     6
 *     8
 *     10
 *     12
 *     16
 *
 * Возвращает:
 *
 *      0 - успешно;
 *     -1 - ошибка или неподдерживаемый порядок.
 */
static inline int gauss_legendre_order_supported(int order)
{
    return order == 2 || order == 3 || order == 4 || order == 5 || order == 6
        || order == 8 || order == 10 || order == 12 || order == 16;
}

int gauss_legendre_rule(int order, double *x, double *w);


/*
 * ============================================================
 * ПЛОЩАДЬ ТРЕУГОЛЬНИКА
 * ============================================================
 *
 * Возвращает:
 *
 *     S = 0.5 * |(p1-p0) x (p2-p0)|.
 *
 * Единицы:
 *
 *     м^2.
 */
double triangle_area(
    const double p0[3],
    const double p1[3],
    const double p2[3]
);


/*
 * ============================================================
 * ПЛОЩАДЬ QUADPATCH
 * ============================================================
 *
 * Quadrangle разбивается на два треугольника:
 *
 *     T0 = (p0,p1,p2)
 *     T1 = (p0,p2,p3).
 */
double quad_patch_area(const QuadPatch *patch);


/*
 * ============================================================
 * ХАРАКТЕРНЫЙ РАЗМЕР QUADPATCH
 * ============================================================
 *
 * Возвращает максимальную длину стороны quadrangle.
 *
 * Используется для классификации NEAR/FAR.
 */
double quad_patch_size(const QuadPatch *patch);


/*
 * ============================================================
 * МИНИМАЛЬНОЕ РАССТОЯНИЕ МЕЖДУ ВЕРШИНАМИ
 * ============================================================
 *
 * Возвращает минимальное расстояние между вершинами
 * двух QuadPatch.
 *
 * Это простая оценка расстояния между областями.
 */
double quad_patch_min_vertex_distance(
    const QuadPatch *a,
    const QuadPatch *b
);


/*
 * ============================================================
 * КЛАССИФИКАЦИЯ ПАРЫ QUADPATCH
 * ============================================================
 *
 * Для NEAR используется критерий:
 *
 *     d_min < near_factor * max(h_a, h_b),
 *
 * где:
 *
 *     d_min - нижняя оценка расстояния по ограничивающим AABB;
 *     h_a   - характерный размер области a;
 *     h_b   - характерный размер области b.
 */
QuadPairType quad_patch_classify_pair(
    const QuadPatch *a,
    const QuadPatch *b,
    double near_factor
);


/*
 * ============================================================
 * ОСНОВНОЙ ДВОЙНОЙ ИНТЕГРАЛ
 * ============================================================
 *
 * Вычисляет:
 *
 *              /        /
 *             |        |       1
 *     K_ab =  |        |    ------- dS dS'
 *             |        |    |r-r'|
 *            /Pi_a    /Pi_b
 *
 *
 * Используются разные порядки квадратуры:
 *
 * far_order
 *     для FAR.
 *
 * near_order
 *     для NEAR.
 *
 * touching_order
 *     для TOUCHING.
 *
 * self_order
 *     для SELF.
 *
 *
 * SELF:
 *     аналитический внутренний интеграл и адаптивная внешняя квадратура.
 *
 * TOUCHING:
 *     аналитический внутренний интеграл и адаптивная внешняя квадратура.
 *
 * NEAR:
 *     аналитический внутренний интеграл и адаптивная внешняя квадратура.
 *
 * FAR:
 *     используется обычный порядок.
 */
double quad_patch_kernel_1_over_r(
    const QuadPatch *a,
    const QuadPatch *b,
    int far_order,
    int near_order,
    int touching_order,
    int self_order,
    double near_factor
);


#endif
