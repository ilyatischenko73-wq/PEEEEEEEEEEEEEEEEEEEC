#ifndef PEEC_INCIDENCE_H
#define PEEC_INCIDENCE_H

#include "mesh.h"
#include "potential.h"
#include "matrix.h"

#include <stddef.h>


/*
 * ============================================================
 * МАТРИЦА ИНЦИДЕНТНОСТИ
 * ============================================================
 *
 * Размер:
 *
 *     A : Ne x Nv,
 *
 * где:
 *
 *     Ne - число глобальных ребер;
 *     Nv - число узлов.
 *
 *
 * Для глобально ориентированного ребра:
 *
 *     e = (a -> b)
 *
 * записываем:
 *
 *     A[e,a] = -1
 *     A[e,b] = +1.
 *
 *
 * Следовательно, каждая строка содержит ровно
 * два ненулевых элемента.
 *
 * Также:
 *
 *     A * 1 = 0.
 *
 *
 * Матрица хранится в row-major формате:
 *
 *     data[e * cols + v].
 */
typedef struct
{
    size_t rows;
    size_t cols;

    double *data;

} IncidenceMatrix;


/*
 * ============================================================
 * ИНИЦИАЛИЗАЦИЯ
 * ============================================================
 */
void incidence_init(
    IncidenceMatrix *A
);


/*
 * ============================================================
 * ОСВОБОЖДЕНИЕ ПАМЯТИ
 * ============================================================
 */
void incidence_free(
    IncidenceMatrix *A
);


/*
 * ============================================================
 * ПОСТРОЕНИЕ МАТРИЦЫ A
 * ============================================================
 *
 * Используется глобальная ориентация ребер,
 * уже построенная в topology.c.
 *
 * Для:
 *
 *     edge e = a -> b
 *
 * устанавливается:
 *
 *     A[e,a] = -1
 *     A[e,b] = +1.
 */
int incidence_build(
    const Mesh *mesh,
    IncidenceMatrix *A
);


/*
 * ============================================================
 * ПРОВЕРКА A * 1 = 0
 * ============================================================
 *
 * Возвращает:
 *
 *     max_e |sum_v A[e,v]|.
 *
 * Для корректной матрицы инцидентности значение
 * должно быть близко к нулю.
 */
double incidence_check_row_sum(
    const IncidenceMatrix *A
);


/*
 * ============================================================
 * ДИАГНОСТИКА
 * ============================================================
 */
void incidence_print_info(
    const IncidenceMatrix *A
);


/*
 * ============================================================
 * K = A P A^T
 * ============================================================
 *
 * Размер:
 *
 *     K : Ne x Ne.
 *
 *
 * Для ребер:
 *
 *     e = (a -> b)
 *     f = (c -> d)
 *
 * при:
 *
 *     A[e,a] = -1
 *     A[e,b] = +1
 *
 *     A[f,c] = -1
 *     A[f,d] = +1
 *
 * получаем:
 *
 *     K[e,f]
 *
 *     = P[a,c]
 *       - P[a,d]
 *       - P[b,c]
 *       + P[b,d].
 *
 *
 * Матрица K использовалась для сокращенной формы системы.
 *
 * В основной классической PEEC-системе она сейчас
 * не требуется, но оставляется для:
 *
 * - диагностики;
 * - сравнений;
 * - тестов;
 * - возможных будущих вариантов решателя.
 */
int incidence_build_APAT(
    const Mesh *mesh,
    const PotentialMatrix *P,
    Matrix *K,
    int parallel_threads
);


/*
 * ============================================================
 * B = P A^T
 * ============================================================
 *
 * Эта матрица непосредственно нужна классической
 * PEEC-системе.
 *
 *
 * Размер:
 *
 *     B = P A^T
 *
 *     B : Nv x Ne.
 *
 *
 * Для глобально ориентированного ребра:
 *
 *     e = (a -> b)
 *
 * матрица инцидентности имеет:
 *
 *     A[e,a] = -1
 *     A[e,b] = +1.
 *
 *
 * Тогда:
 *
 *     B[j,e]
 *
 *     = sum_k P[j,k] A^T[k,e]
 *
 *     = sum_k P[j,k] A[e,k]
 *
 *     = -P[j,a] + P[j,b].
 *
 *
 * Поэтому:
 *
 *     (P A^T)[j,e]
 *
 *     = P[j,b] - P[j,a].
 *
 *
 * Благодаря разреженности A обычное плотное
 * умножение P * A^T выполнять не требуется.
 *
 *
 * Эта матрица входит в классическую PEEC-систему:
 *
 *     L dI/dt + R I + A V = -U_e
 *
 *     dV/dt - P A^T I = P I_s.
 *
 *
 * В частотной области:
 *
 *     (R + j*w*L) I + A V = -U_e
 *
 *     -P A^T I + j*w V = P I_s.
 */
int incidence_build_PAT(
    const Mesh *mesh,
    const PotentialMatrix *P,
    Matrix *PAT,
    int parallel_threads
);



/*
 * ============================================================
 * B = A S
 * ============================================================
 *
 * Для transient-системы с собственным узловым напряжением:
 *
 *     V_cj = q_j / F_j,
 *
 *     F_j  = 1 / P_jj,
 *
 *     S_ja = P_ja / P_aa.
 *
 *
 * Матрица:
 *
 *     B = A S
 *
 * имеет размер:
 *
 *     Ne x Nv.
 *
 *
 * Для ребра:
 *
 *     e = (m -> n),
 *
 * где:
 *
 *     A[e,m] = -1,
 *     A[e,n] = +1,
 *
 * получаем:
 *
 *     (A S)[e,a]
 *
 *     =
 *
 *     (P[n,a] - P[m,a]) / P[a,a].
 *
 *
 * Полная матрица S при этом явно не строится.
 */
int incidence_build_AS(
    const IncidenceMatrix *A,
    const PotentialMatrix *P,
    Matrix *AS,
    int parallel_threads
);


#endif
